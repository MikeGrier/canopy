# tools/gen-quotient-soundness.ps1 -- write crates/canopy/spec/QuotientSoundnessPair.tla and every
# crates/canopy/spec/QuotientSoundness*.cfg.
#
# Usage:
#   pwsh tools/gen-quotient-soundness.ps1
#
# QuotientSoundnessPair.tla is the second copy of the SharedPublicationCheck composition that
# QuotientSoundness.tla checks the first against: a b_ variable for every variable the composition
# declares, read from the VARIABLES of CoordinationState.tla and SharedPublication.tla, so a variable
# added there reaches the copy when this is rerun. Each configuration takes its constants from the
# SharedPublicationCheck configuration its table entry names and states in its header what TLC must
# report, which tools/run-tlc-all.ps1 reads. Regenerating changes no file when nothing it reads has
# changed. Output is LF and 7-bit ASCII.

param(
    [string]$SpecDirectory = (Join-Path (Split-Path -Parent $PSScriptRoot) 'crates/canopy/spec')
)

$ErrorActionPreference = 'Stop'
$spec = $SpecDirectory
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Get-Variables([string]$path) {
    $names = @()
    $inBlock = $false
    foreach ($line in [IO.File]::ReadAllLines($path)) {
        if (-not $inBlock) {
            if ($line -match '^VARIABLES\s*$') { $inBlock = $true }
            continue
        }
        $code = ($line -replace '\\\*.*$', '').Trim()
        if ($code -eq '') { continue }
        $names += @($code -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ -match '^\w+$' })
        if (-not $code.EndsWith(',')) { break }
    }
    if ($names.Count -eq 0) { throw "no VARIABLES block in $path" }
    return $names
}

$names = @(Get-Variables (Join-Path $spec 'CoordinationState.tla')) +
         @(Get-Variables (Join-Path $spec 'SharedPublication.tla'))
$dups = @($names | Group-Object | Where-Object Count -gt 1 | ForEach-Object Name)
if ($dups.Count -gt 0) { throw "variables declared twice: $($dups -join ', ')" }

function Join-Wrapped([string[]]$items, [string]$indent, [string]$separator) {
    $out = @()
    $line = $indent
    for ($i = 0; $i -lt $items.Count; $i++) {
        $piece = $items[$i] + $(if ($i -lt $items.Count - 1) { $separator.TrimEnd() } else { '' })
        if ($line.Length -gt $indent.Length -and ($line.Length + 1 + $piece.Length) -gt 96) {
            $out += $line
            $line = $indent
        }
        $line += $(if ($line.Length -gt $indent.Length) { ' ' } else { '' }) + $piece
    }
    $out += $line
    return $out
}

$copies = $names | ForEach-Object { "b_$_" }
$lines = @(
    '\* Copyright (c) Michael Grier.',
    '\* Generated by tools/gen-quotient-soundness.ps1 from the VARIABLES of CoordinationState.tla and',
    '\* SharedPublication.tla. Rerun it when a variable is added or removed; never edit this file.',
    '---------------------- MODULE QuotientSoundnessPair -----------------------',
    'EXTENDS SharedPublicationCheck',
    '',
    'VARIABLES'
)
$lines += Join-Wrapped $copies '    ' ', '
$lines += ''
$lines += '\* The second copy of the composition, over the b_ variables.'
$lines += 'B == INSTANCE SharedPublicationCheck WITH'
for ($i = 0; $i -lt $names.Count; $i++) {
    $lines += '    {0} <- b_{0}{1}' -f $names[$i], $(if ($i -lt $names.Count - 1) { ',' } else { '' })
}
$lines += ''
$lines += 'bvars =='
$lines += '    <<' + ((Join-Wrapped $copies '' ', ') -join "`n      ") + '>>'
$lines += ''
$lines += '\* Every variable of the first copy, by name.'
$lines += 'Snap =='
$lines += '    [' + ((Join-Wrapped ($names | ForEach-Object { "$_ |-> $_" }) '' ', ') -join "`n     ") + ']'
$lines += ''
$lines += '\* The second copy takes the state s, a record shaped as Snap.'
$lines += 'LoadB(s) =='
foreach ($n in $names) { $lines += "    /\ b_$n' = s.$n" }
$lines += ''
$lines += '============================================================================='
[IO.File]::WriteAllText((Join-Path $spec 'QuotientSoundnessPair.tla'), ($lines -join "`n") + "`n", $utf8)

# Configurations: name, the SharedPublicationCheck configuration whose constants it uses, whether
# it checks the view known to forget the fence, what it is, its tier, and the constants it sets
# differently.
$configs = @(
    @('QuotientSoundness-Publication', 'SharedPublicationCheck-PublicationUnits', $false,
      'One writer publishes to one document', 'item', @{}),
    @('QuotientSoundness-Transaction', 'SharedPublicationCheck-TransactionUnits', $false,
      'One writer transacts on one document', 'item', @{}),
    @('QuotientSoundness-StaleRecovery', 'SharedPublicationCheck-StaleRecoverySchedule', $false,
      'Two writers resume a stale recovery on one document', 'item', @{}),
    @('QuotientSoundness-NodeRemoval', 'SharedPublicationCheck-Witness-ATransactionRemovesANode', $false,
      'One namespace tree removes a node', 'evidence', @{ MaxRequests = '1' }),
    @('QuotientSoundness-TwoWriters', 'SharedPublicationCheck-Witness-WriterRefusedBetweenUnits', $false,
      'Two writers of one write each on one document, either recovering', 'milestone',
      @{ MaxWrites = '1'; MaxRequests = '9' }),
    @('QuotientSoundness-Control-ViewForgetsTheFence', 'SharedPublicationCheck-PublicationUnits', $true,
      'Negative control: the checked view forgets the fence, which recovery reads', 'item', @{})
)

$directoryRegions = @(
    @('Transaction', 'directory-creation-transaction'),
    @('AppendPlan', 'directory-creation-append-plan'),
    @('AppendRepair', 'directory-creation-append-repair'),
    @('AppendSync', 'directory-creation-append-sync'),
    @('Create', 'directory-creation-create'),
    @('Sync', 'directory-creation-sync'),
    @('Complete', 'directory-creation-complete'),
    @('Recovery', 'directory-creation-recovery')
)
foreach ($region in $directoryRegions) {
    $configs += ,@(
        "QuotientSoundness-DirectoryCreation-$($region[0])",
        'SharedPublicationCheck-Witness-ADirectoryIntentIsRepaired',
        $false,
        'One absent node recreates through a torn directory intent and recovery',
        'evidence',
        @{ MaxRequests = '1'; NPtr = '1' },
        'all',
        $region[1])
}

Get-ChildItem $spec -File -Filter 'QuotientSoundness*.cfg' | Remove-Item
foreach ($c in $configs) {
    $base = Join-Path $spec "$($c[1]).cfg"
    $constants = @()
    $inConstants = $false
    foreach ($line in [IO.File]::ReadAllLines($base)) {
        if ($line -eq 'CONSTANTS') { $inConstants = $true; continue }
        if ($inConstants -and $line -match '^\s+(\w+) = ') {
            $constants += $(if ($c[5].ContainsKey($Matches[1])) { "    $($Matches[1]) = $($c[5][$Matches[1]])" } else { $line })
            continue
        }
        if ($inConstants) { break }
    }
    if ($constants.Count -eq 0) { throw "no CONSTANTS in $base" }
    $out = @('\* Copyright (c) Michael Grier.')
    if ($c[2]) {
        $out += "\* $($c[3])."
        $out += '\* TLC must report a deadlock.'
    } else {
        $out += "\* $($c[3])."
        $out += '\* Every selected perturbation of what the view forgets is answered step for step:'
        $out += '\* every invariant and property holds.'
    }
    if ($c[4] -ne 'item') { $out += "\* Tier: $($c[4])." }
    $out += 'CONSTANTS'
    $out += $constants
    $out += "    ViewControl = $(if ($c[2]) { 'TRUE' } else { 'FALSE' })"
    $focus = if ($c[0] -eq 'QuotientSoundness-NodeRemoval') { 'node-removal' }
             elseif ($c.Count -gt 7) { $c[7] }
             else { 'all' }
    $out += "    SoundnessFocus = `"$focus`""
    $partition = if ($c.Count -gt 6) { $c[6] } else { 'all' }
    $out += "    SoundnessPerturbation = `"$partition`""
    $out += 'SPECIFICATION SoundnessSpec'
    if ($c[0] -eq 'QuotientSoundness-NodeRemoval') {
        $out += 'CONSTRAINT RemovalSoundnessScope'
    } elseif ($c[0].StartsWith('QuotientSoundness-DirectoryCreation-')) {
        $out += 'CONSTRAINT WriteSoundnessScope'
    } else {
        $out += 'CONSTRAINT QuotientTypeOK'
    }
    $out += 'VIEW ProductView'
    $out += 'INVARIANTS'
    $out += '    SameView'
    if (-not $c[2]) { $out += '    FactsAgree' }
    $out += 'CHECK_DEADLOCK TRUE'
    [IO.File]::WriteAllText((Join-Path $spec "$($c[0]).cfg"), ($out -join "`n") + "`n", $utf8)
}

'wrote QuotientSoundnessPair.tla ({0} variables) and {1} configurations' -f $names.Count, $configs.Count
